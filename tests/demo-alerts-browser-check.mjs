import assert from 'node:assert/strict';
import {mkdir,mkdtemp,writeFile,readFile} from 'node:fs/promises';
import {join} from 'node:path';
import {pathToFileURL} from 'node:url';
import {localDatabase} from '../Backend/tests/local-fixture.mjs';
import {createApp} from '../Backend/src/server.mjs';
import {createDemoAlerts} from '../Backend/src/demo-alerts.mjs';
import {opaqueToken,tokenDigest} from '../Backend/src/auth.mjs';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright');
await mkdir(new URL('../.tmp/',import.meta.url),{recursive:true});
const root=await mkdtemp(new URL('../.tmp/demo-browser-',import.meta.url));
const fixture=await localDatabase(),feedPath=join(root,'feed.json');
await writeFile(feedPath,await readFile(new URL('../assets/demo-alert-feed.json',import.meta.url)));
const service=createDemoAlerts({pool:fixture.pool,feedPath,intervalMs:100});
let browser,server;
try{
 await service.start();
 await fixture.pool.query("INSERT INTO attendance.users(id,email,password_hash,role) VALUES('00000000-0000-4000-8000-000000000001','demo@test.local','NONLOGIN','teacher')");
 const token=opaqueToken();
 await fixture.pool.query("INSERT INTO attendance.auth_sessions(token_hash,user_id,csrf_token,expires_at) VALUES($1,'00000000-0000-4000-8000-000000000001',$2,now()+interval '1 hour')",[tokenDigest(token),opaqueToken()]);
 server=createApp({pool:fixture.pool,publicOrigin:'http://127.0.0.1:39219',demoAlerts:service,faceWorker:{close(){}}});
 await new Promise(resolve=>server.listen(39219,'127.0.0.1',resolve));
 browser=await chromium.launch({headless:true,...(process.env.CHROME_EXECUTABLE ? {executablePath:process.env.CHROME_EXECUTABLE} : {channel:'chrome'})});
 const page=await browser.newPage({viewport:{width:1280,height:900}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.context().addCookies([{name:'presence_session',value:token,url:'http://127.0.0.1:39219',httpOnly:true}]);
 await page.goto('http://127.0.0.1:39219/demo-alerts.html');
 await page.locator('#record option[value="demo-orion-01"]').waitFor({state:'attached'});
 await page.locator('#record').selectOption('demo-orion-01');await page.locator('#simulate').click();
 await page.getByRole('heading',{name:'DEMO — Faculty security is getting informed',exact:true}).waitFor();
 await page.screenshot({path:join(root,'desktop.png'),fullPage:true});
 await writeFile(feedPath,JSON.stringify({records:[{id:'demo-new',name:'Fictional New',scenario:'Updated synthetic scenario',synthetic:true,fictional:true}]}));
 await page.waitForFunction(async()=>{const r=await fetch('/api/demo-alerts');return (await r.json()).records.some(r=>r.id==='demo-new');});
 await page.locator('#refresh').click();await page.locator('#record option[value="demo-new"]').waitFor({state:'attached'});
 assert.equal(await page.locator('#record option[value="demo-orion-01"]').count(),0);
 await page.setViewportSize({width:390,height:844});await page.screenshot({path:join(root,'mobile.png'),fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 assert.deepEqual(errors,[]);console.log('Browser checks passed; screenshots: '+root);
}finally{service.stop();await browser?.close();if(server)await new Promise(resolve=>server.close(resolve));await fixture.engine.close();}
